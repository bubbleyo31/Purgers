/// <summary>
/// 所有具有「存活 / 死亡」概念的戰鬥物件
/// 可以實作這個標準接口。
///
/// ------------------------------------------------------------
///
/// 這個接口不負責：
///
/// 扣血
/// 傷害計算
/// 死亡動畫
/// 掉落物
/// 專注技能
///
/// 它只提供一個非常單純的戰鬥狀態：
///
/// 這個目標現在到底是不是活著。
///
/// ------------------------------------------------------------
///
/// 未來可以由：
///
/// TestDamageReceiver
/// EnemyHealth
/// BossHealth
/// PlayerHealth
///
/// 實作。
///
/// ------------------------------------------------------------
///
/// 其他系統例如：
///
/// Focus Auto Lock
/// Enemy Target Selection
/// Aim Assist
/// AI Target Search
///
/// 都可以只讀這個接口，
/// 不需要知道目標到底使用哪一種 Health Component。
/// </summary>
public interface ICombatLifeState
{
    /// <summary>
    /// 目標目前是否仍然存活。
    ///
    /// true：
/// 可以正常被視為戰鬥中的活體目標。
    ///
    /// false：
/// 已經死亡，不應再被一般戰鬥目標搜尋選中。
    /// </summary>
    bool IsAlive
    {
        get;
    }

    /// <summary>
    /// 目標目前是否死亡。
    ///
    /// 這是 IsAlive 的反向資訊，
/// 方便其他系統直接閱讀。
    /// </summary>
    bool IsDead
    {
        get;
    }
}